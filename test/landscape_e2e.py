# Browser test of landscape mode (phone turned sideways) against test/dev.js. Run: python3 test/landscape_e2e.py
import json, datetime, urllib.request as u
from playwright.sync_api import sync_playwright
BASE='http://127.0.0.1:8790'
H={'Authorization':'Bearer dev-admin','Content-Type':'application/json'}
post=lambda path,body: json.loads(u.urlopen(u.Request(BASE+path, data=json.dumps(body).encode(), headers=H, method='POST')).read())
now=datetime.datetime.now(datetime.timezone.utc); issues=[]
for ago,m,a,c in [(0,'Metro',30,'Visa'),(1,'Uber Eats',24,'Amex'),(2,'Tim Hortons',6,'Visa'),(3,'Costco',90,'Amex'),(5,'Netflix',15,'Visa'),(8,'Lyft',20,'Visa'),(40,'Costco',140,'Amex'),(70,'Metro',60,'Visa'),(120,'Costco',80,'Amex')]:
    t=(now-datetime.timedelta(days=ago)).replace(hour=15,minute=0,second=0,microsecond=0); iso=t.strftime('%Y-%m-%dT%H:%M:%SZ')
    issues.append({"title":f"Spending - ${a} - {iso[:10]}","body":f"Date: {iso}\nMerchant: {m}\nAmount: ${a}\nCard: {c}\nCategory: ","state":"open","created_at":iso})
res=[]; errs=[]
def ok(c,l): res.append(bool(c)); print(('  ok ' if c else '  FAIL ')+l)
with sync_playwright() as P:
    b=P.chromium.launch(executable_path='/usr/bin/google-chrome',args=['--no-sandbox'])
    ctx=b.new_context(viewport={'width':844,'height':390},device_scale_factor=2,has_touch=True)
    pg=ctx.new_page(); pg.on('pageerror',lambda e: errs.append(str(e)))
    vis=lambda s: pg.locator(s).is_visible()
    pg.goto(BASE+'/?invite='+post('/api/admin/invites',{})['code']); pg.wait_for_timeout(600)
    f=pg.locator('#auth-form').bounding_box(); h1=pg.locator('#signin h1').bounding_box()
    ok(f['x']>h1['x']+h1['width']*0.6 and f['y']<390,'sign-in is two columns: the intro on the left, the form on the right')
    pg.screenshot(path='/tmp/claude-0/ls-signin.png')
    pg.fill('#auth-email','ls@example.com'); pg.fill('#auth-password','landscape-pw-12345'); pg.click('#auth-submit'); pg.wait_for_timeout(1000)
    post('/api/admin/import',{"email":"ls@example.com","issues":issues,"dailyLimit":100})
    pg.click('#tour-skip'); pg.wait_for_timeout(800); pg.click('#onboard-done'); pg.wait_for_timeout(4000)
    ok(vis('#history-sheet'),'turned sideways, the spending report opens by itself')
    bb=pg.locator('#history-sheet').bounding_box()
    ok(bb['width']>=840 and bb['height']>=385,'the report fills the whole screen')
    vh=lambda s: pg.evaluate("s=>{const e=document.querySelector(s);return !!e&&getComputedStyle(e).display!=='none'&&e.getBoundingClientRect().width>0}",s)
    ok(pg.locator('.hist-wk').count()>=4,'the calendar has a Week column with each week\'s total')
    ok(not any(vh(x) for x in ('.hc-total','.hc-kpi','.hc-cats','.hc-cards','.hc-merch','.hc-heat','.hc-months','.hist-seg','.hist-top h2')),'Clean landscape hides totals, categories, cards, merchants and heatmaps')
    ys=pg.evaluate("[...document.querySelectorAll('.hist-top > *')].filter(e=>e.getBoundingClientRect().width>0).map(e=>Math.round(e.getBoundingClientRect().top+e.getBoundingClientRect().height/2))")
    ok(len(set(ys))==1,'the controls share one aligned row '+str(ys))
    ok(pg.locator('.hist-range option').all_inner_texts()==['Week','Month'],'the range picker offers only Week and Month')
    ok(pg.locator('.hist-top .lv button').count()==3,'Calendar, Chart and List switch sits in the top row')
    ok(pg.evaluate("document.documentElement.scrollWidth<=innerWidth"),'no sideways overflow')
    pg.screenshot(path='/tmp/claude-0/ls-month.png')
    pg.click('.lv button >> text=Chart'); pg.wait_for_timeout(500)
    ok(vh('.hist-read') and pg.locator('.hist-days .hist-dc').count()>=28,'Chart shows bars with a readout line')
    pg.click('.lv button >> text=List'); pg.wait_for_timeout(500)
    ok(pg.locator('.hist-tx').count()>=1,'List shows the purchases')
    pg.select_option('.hist-range','week'); pg.wait_for_timeout(1000)
    ok(pg.locator('.hist-range').input_value()=='week','Week range works')
    pg.click('.lv button >> text=Calendar'); pg.wait_for_timeout(300)
    pg.screenshot(path='/tmp/claude-0/ls-week.png')
    pg.click('#history-sheet .link'); pg.wait_for_timeout(500)
    ok(not vis('#history-sheet'),'the close button closes the report')
    pg.wait_for_timeout(1500)
    ok(not vis('#history-sheet'),'and it stays closed while the phone is still sideways')
    ok(pg.evaluate("getComputedStyle(document.querySelector('.stack')).columnCount")=='2','the home page is in two columns')
    pg.screenshot(path='/tmp/claude-0/ls-home.png')
    pg.click('#settings-open'); pg.wait_for_timeout(500)
    sb=pg.locator('#settings-sheet').bounding_box()
    ok(sb['x']>200 and sb['height']>=385,'panels slide in from the right and use the full height')
    pg.screenshot(path='/tmp/claude-0/ls-settings.png')
    pg.click('#settings-close'); pg.wait_for_timeout(300)
    # turn back to portrait and sideways again
    pg.set_viewport_size({'width':390,'height':844}); pg.wait_for_timeout(600)
    ok(not vis('#history-sheet') and pg.evaluate("getComputedStyle(document.querySelector('.stack')).columnCount")=='auto','back in portrait it is the normal single column')
    pg.set_viewport_size({'width':844,'height':390}); pg.wait_for_timeout(1500)
    ok(vis('#history-sheet'),'turning sideways again opens the report again')
    pg.set_viewport_size({'width':390,'height':844}); pg.wait_for_timeout(600)
    ok(not vis('#history-sheet'),'turning back closes it')
    ok(not errs,'no page errors '+str(errs))
    b.close()
print('\nALL PASSED: %d'%len(res) if all(res) else '\nFAILURES: %d'%res.count(False))
